"""
Module 6 — Monitoring Dashboard.

A single-page Streamlit dashboard that shows:
  1. Live drift status (re-runs the KS-test experiment from detect_drift.py)
  2. SHAP explainability plots (from reports/, generated by explain_model.py)
  3. The latest Gemini diagnostic report (from reports/)
  4. Model version history / retraining log (from outputs/retraining_log.csv,
     generated by retrain_validate.py)

Run with:  streamlit run app.py
"""

from pathlib import Path

import pandas as pd
import streamlit as st
from scipy.stats import ks_2samp

ROOT = Path(__file__).resolve().parent
DATA_PATH = ROOT / "data" / "Telco-Customer-Churn.csv"
REPORT_DIR = ROOT / "reports"
LOG_PATH = ROOT / "outputs" / "retraining_log.csv"

st.set_page_config(page_title="DataDrift-Shield Dashboard", layout="wide")
st.title("DataDrift-Shield — Monitoring Dashboard")
st.caption(
    "Self-healing ML pipeline: drift detection -> SHAP explanation -> "
    "Gemini report -> validated retraining."
)

# ---------------------------------------------------------------------
# 1. Live drift status
# ---------------------------------------------------------------------
st.header("1. Drift status")

if DATA_PATH.exists():
    df = pd.read_csv(DATA_PATH)
    df["TotalCharges"] = pd.to_numeric(df["TotalCharges"], errors="coerce")
    features = ["tenure", "MonthlyCharges", "TotalCharges"]
    clean = df[features].dropna()

    reference = clean.sample(frac=0.70, random_state=42)
    incoming = clean.drop(reference.index).copy()

    shift_pct = st.slider(
        "Simulated shift in MonthlyCharges for the incoming batch (%)",
        min_value=0, max_value=50, value=20, step=5,
    )
    shifted = incoming.copy()
    shifted["MonthlyCharges"] *= 1 + shift_pct / 100

    rows = []
    for feature in features:
        result = ks_2samp(reference[feature], shifted[feature])
        rows.append({
            "feature": feature,
            "ks_statistic": round(float(result.statistic), 4),
            "p_value": round(float(result.pvalue), 6),
            "status": "DRIFT" if result.pvalue < 0.05 else "No drift",
        })
    status_df = pd.DataFrame(rows)

    def highlight(row):
        color = "background-color:#ffd6d6" if row["status"] == "DRIFT" else ""
        return [color] * len(row)

    st.dataframe(status_df.style.apply(highlight, axis=1), use_container_width=True)
else:
    st.warning("Dataset not found in data/. Add Telco-Customer-Churn.csv to see live drift status.")

# ---------------------------------------------------------------------
# 2. SHAP explainability
# ---------------------------------------------------------------------
st.header("2. SHAP explainability")

col1, col2 = st.columns(2)
bar_path = REPORT_DIR / "shap_feature_importance.png"
beeswarm_path = REPORT_DIR / "shap_summary.png"

with col1:
    if bar_path.exists():
        st.image(str(bar_path), caption="Global feature importance")
    else:
        st.info("Run src/explain_model.py to generate this plot.")

with col2:
    if beeswarm_path.exists():
        st.image(str(beeswarm_path), caption="SHAP summary (beeswarm)")
    else:
        st.info("Run src/explain_model.py to generate this plot.")

# ---------------------------------------------------------------------
# 3. Gemini diagnostic report
# ---------------------------------------------------------------------
st.header("3. Latest GenAI diagnostic report")

report_path = REPORT_DIR / "gemini_diagnostic_report.md"
if report_path.exists():
    st.markdown(report_path.read_text(encoding="utf-8"))
else:
    st.info("Run src/generate_report.py to generate the Gemini diagnostic report.")

# ---------------------------------------------------------------------
# 4. Model version history / retraining log
# ---------------------------------------------------------------------
st.header("4. Model version history & retraining log")

if LOG_PATH.exists():
    log_df = pd.read_csv(LOG_PATH)
    st.dataframe(log_df, use_container_width=True)
    st.caption(
        "A challenger model is only promoted to production (\"champion\") "
        "when it beats the current champion's ROC-AUC on the same test set."
    )
else:
    st.info("Run src/retrain_validate.py at least once to populate this log.")
